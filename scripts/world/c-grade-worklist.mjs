#!/usr/bin/env node
/**
 * Which places are graded C, and what each one needs.
 *
 *   npx vite-node scripts/world/c-grade-worklist.mjs
 *
 * Writes docs/world/C-GRADE-WORKLIST.md. Generated — run it again rather than editing it.
 *
 * Why a list and not a test. The brief says only A and B places may be quest destinations,
 * and the ticket that enforced it would have removed «Είμαι εδώ!» from every C place. On
 * 18 Σεπτεμβρίου that was 31 places in ten of the twelve cities outside Greece: ten cities
 * could never have been sealed and 29 places would have left their trails. Nineteen of the
 * 31 were C only because OpenStreetMap did not answer the night they were resolved. The
 * owner chose a worklist over a block: re-resolve first, then apply the rule to what is
 * still C.
 *
 * Two kinds of C, and they are fixed differently:
 *
 *   no OSM cross-check  → re-run `resolve-coords.mjs <city>` once Overpass answers a whole
 *                         batch (not a single query). Most become B. Keep a clean run;
 *                         never commit a partial one.
 *   OSM present, still C → one source genuinely disagrees. Re-seed (usually the wrong
 *                         Wikidata item — the building, not the institution) or, in
 *                         Greece, the owner walks it and records the door.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const OUT = path.join(ROOT, 'docs', 'world', 'C-GRADE-WORKLIST.md');

const { CITY_IDS, CITIES, loadCity } = await import(path.join(ROOT, 'data', 'world', 'registry.ts'));

const rows = [];
for (const cityId of CITY_IDS) {
  const city = CITIES.find((c) => c.id === cityId);
  if (!city) continue;
  const coordsPath = path.join(ROOT, 'data', 'world', 'coords', `${cityId}.json`);
  const coords = fs.existsSync(coordsPath) ? JSON.parse(fs.readFileSync(coordsPath, 'utf8')) : { places: [] };
  const byId = new Map(coords.places.map((p) => [p.id, p]));
  const module = await loadCity(cityId);
  const inTrail = new Set((module.trails ?? []).flatMap((t) => t.placeIds));

  for (const place of module.places) {
    if (place.location.confidence !== 'C') continue;
    const resolved = byId.get(place.id);
    const osm = (resolved?.sources ?? place.location.sources ?? []).some((s) => s.kind === 'osm');
    rows.push({
      cityId,
      greek: city.countryId === 'greece',
      id: place.id,
      name: place.name?.en ?? place.id,
      trail: inTrail.has(place.id),
      osm,
    });
  }
}

const abroad = rows.filter((r) => !r.greek);
const greece = rows.filter((r) => r.greek);
const need = (r) => (r.osm ? 'one source disagrees: re-seed' : 'no OSM: re-resolve first');

const table = (list) => {
  const lines = ['| City | Place | In a trail | What it needs |', '| --- | --- | --- | --- |'];
  for (const r of list) lines.push(`| ${r.cityId} | ${r.name} (\`${r.id}\`) | ${r.trail ? 'yes' : 'no'} | ${need(r)} |`);
  return lines.join('\n');
};

const count = (list, f) => list.filter(f).length;

const md = `# C-grade places — the worklist

Generated by \`scripts/world/c-grade-worklist.mjs\`. Do not edit by hand; run it again.

A C grade means one source placed the pin and nothing independent confirmed it. The brief
allows only A and B inside quests. On 18 Σεπτεμβρίου 2026 the owner chose a **worklist,
not a block**: nothing changes for a child today, the places below are re-resolved when
OpenStreetMap answers reliably, and the rule is then applied to whatever is still C.

| | Places | In a trail | No OSM cross-check |
| --- | --- | --- | --- |
| Outside Greece | ${abroad.length} | ${count(abroad, (r) => r.trail)} | ${count(abroad, (r) => !r.osm)} |
| Greece | ${greece.length} | ${count(greece, (r) => r.trail)} | ${count(greece, (r) => !r.osm)} |

**Order of work.** Re-resolve the "no OSM" rows first, one city at a time, only when
Overpass answers a whole seventeen-query batch — a partial run moves the drift instead of
fixing it (London, 14 Σεπτεμβρίου: three runs gave 8, 9 and 8 of 17). Keep a clean run,
never commit a partial one, never hand-edit a grade. The "one source disagrees" rows need
a better seed, usually the building's Wikidata item rather than the institution's. Greek
C places are upgraded by the owner walking to them, per the decisions table.

## Outside Greece

${abroad.length ? table(abroad) : 'None.'}

## Greece — the owner's walk

${greece.length ? table(greece) : 'None.'}
`;

fs.writeFileSync(OUT, md);
console.log(`wrote ${path.relative(ROOT, OUT)} — ${abroad.length} outside Greece, ${greece.length} in Greece`);
