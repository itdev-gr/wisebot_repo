const cache: Record<number, Promise<Record<string, QuizQuestion[]>>> = {};

/** All question arrays of one grade, keyed '<grade>/<subject>/<unit>'. Cached after first load. */
export function loadGradeQuestions(grade: number): Promise<Record<string, QuizQuestion[]>> {
  if (!loaders[grade]) return Promise.resolve({});
  return (cache[grade] ??= loaders[grade]().then(m => m.QUESTIONS));
}
